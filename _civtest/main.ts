import * as THREE from 'three';
import { GeoData } from '../src/world/GeoData';
import { NavGraph } from '../src/nav/NavGraph';
import { Pathfinder } from '../src/nav/Pathfinder';
import { GameRenderer } from '../src/render/GameRenderer';
import { Terrain } from '../src/world/Terrain';
import { Water } from '../src/world/Water';
import { Cities } from '../src/world/Cities';
import { RoadRenderer } from '../src/nav/RoadRenderer';
import { UnitManager } from '../src/units/UnitManager';
import { CivilianSystem } from '../src/civil/CivilianSystem';
import { DEFAULT_SETTINGS } from '../src/core/types';
(async () => {
  const settings = { ...DEFAULT_SETTINGS, pixelScale: 1 };
  const geo = await GeoData.load('/data/');
  const graph = await NavGraph.load(geo, '/data/');
  const pf = new Pathfinder(geo, graph);
  const canvas = document.getElementById('c') as HTMLCanvasElement;
  canvas.width = 1280; canvas.height = 720;
  const gfx = new GameRenderer(canvas, settings);
  const terrain = new Terrain(geo, settings);
  const water = new Water(geo, settings, terrain.heightTexture);
  const cities = new Cities(geo, settings);
  const roads = new RoadRenderer(geo, graph, settings);
  gfx.scene.add(terrain.object, water.object, roads.object, cities.object);
  const units = new UnitManager(geo, pf as any, settings);
  const civ = new CivilianSystem({ geo, units, graph, pathfinder: pf, cities, settings });
  gfx.scene.add(civ.object);
  const cam = new THREE.PerspectiveCamera(32, 1280 / 720, 0.5, 30000);
  let t = 0, run = true;
  const w = window as any;
  w.civ = civ; w.cities = cities;
  w.look = (name: string, dist: number) => {
    const c = civ.cities.find((q) => q.name === name)!;
    const gy = Math.max(0, geo.heightAt(c.x, c.z)) * settings.heightExaggeration;
    const pitch = dist > 100 ? 62 : 42;
    const p = pitch * Math.PI / 180;
    cam.position.set(c.x, gy + dist * Math.sin(p), c.z + dist * Math.cos(p));
    cam.lookAt(c.x, gy, c.z); cam.updateMatrixWorld();
  };
  w.lookXZ = (x: number, z: number, dist: number) => { const gy = Math.max(0, geo.heightAt(x, z)) * settings.heightExaggeration; const p = 40 * Math.PI / 180; cam.position.set(x, gy + dist * Math.sin(p), z + dist * Math.cos(p)); cam.lookAt(x, gy, z); cam.updateMatrixWorld(); };
  w.step = (n: number, dh: number) => { for (let i = 0; i < n; i++) civ.update(dh, 0.016, cam); };
  const loop = () => { t += 0.016; terrain.update(cam, t); water.update(cam, t); cities.update(cam); roads.update(cam); civ.update(run ? 0.0003 : 0, 0.016, cam); gfx.render(cam, t); requestAnimationFrame(loop); };
  loop(); w.ready = true;
})().catch((e) => { console.error(e); (window as any).err = String(e); });
