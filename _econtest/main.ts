import '@fontsource/share-tech-mono';
import '../src/ui/styles.css';
import '../src/control/styles-control.css';
import '../src/ui/production.css';
import { Input } from '../src/core/Input';
import { DEFAULT_SETTINGS } from '../src/core/types';
import { RTSCamera } from '../src/camera/RTSCamera';
import { GeoData } from '../src/world/GeoData';
import { Terrain } from '../src/world/Terrain';
import { Water } from '../src/world/Water';
import { GameRenderer } from '../src/render/GameRenderer';
import { NavGraph } from '../src/nav/NavGraph';
import { Pathfinder } from '../src/nav/Pathfinder';
import { RoadRenderer } from '../src/nav/RoadRenderer';
import { UnitManager } from '../src/units/UnitManager';
import { UnitRenderer } from '../src/units/UnitRenderer';
import { War } from '../src/game/War';
import { Effects } from '../src/fx/Effects';
import { OilEconomy } from '../src/logistics/OilEconomy';
import { SupplySystem } from '../src/logistics/SupplySystem';
import { ProductionSystem } from '../src/production/ProductionSystem';
import { EconomyAI } from '../src/logistics/EconomyAI';
import { ProductionPanel } from '../src/ui/ProductionPanel';

async function boot() {
  const settings = { ...DEFAULT_SETTINGS };
  const canvas = document.getElementById('game-canvas') as HTMLCanvasElement;
  const ui = document.getElementById('ui') as HTMLElement;
  const geo = await GeoData.load();
  const graph = await NavGraph.load(geo);
  const pf = new Pathfinder(geo, graph);
  const gfx = new GameRenderer(canvas, settings);
  const terrain = new Terrain(geo, settings);
  const water = new Water(geo, settings, terrain.heightTexture);
  const roads = new RoadRenderer(geo, graph, settings);
  gfx.scene.add(terrain.object, water.object, roads.object);
  const input = new Input(canvas);
  const rts = new RTSCamera(canvas, input, geo, settings);
  const units = new UnitManager(geo, pf, settings);
  const ur = new UnitRenderer(units, geo, settings);
  gfx.scene.add(ur.object);
  const effects = new Effects(geo, settings);
  gfx.scene.add(effects.object);
  const war = new War();
  war.declare('KRN', 'VAL'); war.declare('KRN', 'MAR');
  const eco = new OilEconomy({ geo, units, pathfinder: pf, war, settings });
  const sup = new SupplySystem({ geo, units, economy: eco, pathfinder: pf, war, settings, getPlayer: () => 'VAL' });
  const prod = new ProductionSystem({ geo, units, economy: eco, settings });
  const ai = new EconomyAI({ geo, economy: eco, production: prod, units, war, getPlayer: () => 'VAL' });
  gfx.scene.add(eco.object, prod.object);
  eco.loadScenario(geo.meta.scenario);
  const panel = new ProductionPanel({ production: prod, economy: eco, supply: sup, getPlayer: () => 'VAL', root: ui, getSelectedIds: () => [] });
  panel.show();
  let hoursPerSec = 0.25;
  const T = { geo, rts, units, eco, sup, prod, ai, panel, war, setSpeed: (h: number) => (hoursPerSec = h), gfx, effects, frames: 0 };
  (window as any).T = T;
  const resize = () => { gfx.setSize(window.innerWidth, window.innerHeight); rts.setAspect(window.innerWidth / window.innerHeight); };
  window.addEventListener('resize', resize); resize();
  rts.focus(150, 100, 330, false);
  let last = performance.now(); const t0 = last;
  const frame = (now: number) => {
    const dt = Math.min(0.1, (now - last) / 1000); last = now; const time = (now - t0) / 1000;
    const h = dt * hoursPerSec;
    rts.update(dt);
    units.update(h);
    eco.update(h, dt); sup.update(h, dt); prod.update(h, dt); ai.update(h);
    terrain.update(rts.camera, time); water.update(rts.camera, time); roads.update(rts.camera);
    ur.update(rts.camera, time, 'VAL');
    effects.update(dt, rts.camera, time, units.units);
    gfx.render(rts.camera, time);
    panel.update(dt);
    T.frames++;
    requestAnimationFrame(frame);
  };
  requestAnimationFrame(frame);
}
boot().catch((e) => { console.error(e); document.title = 'ERR ' + e; });
